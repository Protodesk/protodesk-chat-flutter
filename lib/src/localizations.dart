/// UI strings only: customer messages, filenames and server subjects are untouched.
class ChatLocalizations {
  ChatLocalizations(this.locale, {Map<ChatText, String> overrides = const {}})
    : overrides = Map.unmodifiable(overrides);
  final Locale locale;
  final Map<ChatText, String> overrides;
  static const supportedLocales = [Locale('en'), Locale('id')];
  static const delegate = _ChatLocalizationsDelegate();
  static const localizationsDelegates = <LocalizationsDelegate<dynamic>>[
    delegate,
    GlobalMaterialLocalizations.delegate,
    GlobalWidgetsLocalizations.delegate,
    GlobalCupertinoLocalizations.delegate,
  ];
  static ChatLocalizations of(BuildContext context) =>
      Localizations.of<ChatLocalizations>(context, ChatLocalizations) ??
      ChatLocalizations(
        Localizations.maybeLocaleOf(context) ?? const Locale('en'),
      );
  String text(ChatText key) =>
      overrides[key] ??
      (locale.languageCode == 'id' ? _id[key] : null) ??
      _en[key]!;
  String number(int value) => value.toString().replaceAllMapped(
    RegExp(r'(\d)(?=(\d{3})+(?!\d))'),
    (m) => '${m[1]}${locale.languageCode == 'id' ? '.' : ','}',
  );
  String format(ChatText key, Map<String, String> arguments) {
    return text(key).replaceAllMapped(
      RegExp(r'\{(\w+)\}'),
      (match) => arguments[match[1]] ?? match[0]!,
    );
  }

  String unread(int count) => format(ChatText.unread, {'count': number(count)});
  String articles(int count) => count == 1
      ? text(ChatText.articleCountOne)
      : format(ChatText.articleCount, {'count': number(count)});
  String title(int? count) => count == null
      ? text(ChatText.support)
      : format(ChatText.supportUnread, {'count': number(count)});
  String status(String value) {
    final key = switch (value) {
      'disconnected' => ChatText.disconnected,
      'connecting' => ChatText.connecting,
      'connected' => ChatText.connected,
      'reconnecting' => ChatText.reconnecting,
      'queued' || 'retryWait' => ChatText.queued,
      'sending' => ChatText.sending,
      'failed' => ChatText.failed,
      'preparing' || 'initiating' => ChatText.preparing,
      'uploading' => ChatText.uploading,
      'scanning' || 'processing' => ChatText.scanning,
      'ready' => ChatText.ready,
      'cancelled' || 'canceled' => ChatText.cancelled,
      'open' => ChatText.open,
      'closed' => ChatText.closed,
      'resolved' => ChatText.resolved,
      'pending' => ChatText.pending,
      'sent' => ChatText.sent,
      'delivered' => ChatText.delivered,
      'read' => ChatText.read,
      _ => ChatText.unknownStatus,
    };
    return text(key);
  }

  String sender(String value) => text(
    value == 'endUser'
        ? ChatText.you
        : value == 'system'
        ? ChatText.system
        : ChatText.agent,
  );

  /// Machine codes remain available through the SDK; never render raw errors.
  String error(String code) => text(
    code.contains('storage') || code.contains('persistence')
        ? ChatText.storageError
        : code.contains('queue_full')
        ? ChatText.queueFullError
        : code.contains('rate') || code.contains('quota')
        ? ChatText.rateLimitError
        : code.contains('session') || code.contains('identity')
        ? ChatText.sessionError
        : code.contains('network') ||
              code.contains('timeout') ||
              code.contains('connection')
        ? ChatText.connectionError
        : code.contains('attachment') || code.contains('upload')
        ? ChatText.attachmentError
        : ChatText.requestError,
  );
}

class _ChatLocalizationsDelegate
    extends LocalizationsDelegate<ChatLocalizations> {
  const _ChatLocalizationsDelegate();
  @override
  bool isSupported(Locale locale) => ['en', 'id'].contains(locale.languageCode);
  @override
  Future<ChatLocalizations> load(Locale locale) =>
      SynchronousFuture(ChatLocalizations(locale));
  @override
  bool shouldReload(_ChatLocalizationsDelegate old) => false;
}

